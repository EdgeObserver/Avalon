"""阿瓦隆角色提示词。

提示词被拆成四段，按顺序拼成 system prompt：

1. 身份卡    —— 我是谁、几号位、什么阵营
2. 规则简报  —— 全局规则 + 任务人数表（每局按人数动态渲染）
3. 角色策略  —— 这个角色的目标、信息优势、行为禁忌
4. 私有信息  —— 由游戏引擎注入（同伙是谁、梅林候选是谁……）
5. 发言规范  —— 输出格式约束

引擎只需要调 build_system_prompt()，不用关心这里的拼接细节。
"""

from __future__ import annotations

# --------------------------------------------------------------------------- #
# 角色常量
# --------------------------------------------------------------------------- #

MERLIN = "梅林"
PERCIVAL = "派西维尔"
LOYAL = "忠臣"
MORGANA = "莫甘娜"
ASSASSIN = "刺客"
MORDRED = "莫德雷德"
OBERON = "奥伯伦"

GOOD_ROLES: tuple[str, ...] = (MERLIN, PERCIVAL, LOYAL)
EVIL_ROLES: tuple[str, ...] = (MORGANA, ASSASSIN, MORDRED, OBERON)
ALL_ROLES: tuple[str, ...] = GOOD_ROLES + EVIL_ROLES

#: 各人数下的任务队伍规模（第 1~5 轮），官方标准表
QUEST_SIZES: dict[int, tuple[int, int, int, int, int]] = {
    5: (2, 3, 2, 3, 3),
    6: (2, 3, 4, 3, 4),
    7: (2, 3, 3, 4, 4),
    8: (3, 4, 4, 5, 5),
    9: (3, 4, 4, 5, 5),
    10: (3, 4, 4, 5, 5),
}


def is_evil(role: str) -> bool:
    """该角色是否属于红方。"""
    if role not in ALL_ROLES:
        raise ValueError(f"未知角色：{role!r}，可选：{ALL_ROLES}")
    return role in EVIL_ROLES


